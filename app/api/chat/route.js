const envGroqKey = process.env.GROQ_API_KEY;
const envAnthropicKey = process.env.ANTHROPIC_API_KEY;

export async function POST(req) {
  let lastUserMsg = "";
  let language = "si";
  let grade = "5";
  let messages = [];

  try {
    const body = await req.json();
    messages = body.messages || [];
    language = body.language || "si";
    grade = String(body.grade || "5");
    const customApiKey = body.customApiKey;

    lastUserMsg =
      [...messages].reverse().find((m) => m.role === "user")?.content || "";

    const activeGroqKey =
      envGroqKey ||
      (customApiKey && typeof customApiKey === "string" && customApiKey.startsWith("gsk_") && customApiKey.length > 20
        ? customApiKey
        : null);

    const systemPrompt = buildSystemPrompt(grade, language);

    const recentMessages = messages.slice(-8).map((m) => ({
      role: m.role === "assistant" ? "assistant" : "user",
      content: m.content || "",
    }));

    // 1. Try Groq API with official current production models
    if (activeGroqKey) {
      const candidateModels = [
        "llama-3.3-70b-versatile",
        "llama-3.1-8b-instant",
        "gemma2-9b-it"
      ];

      for (const mod of candidateModels) {
        const modelCtrl = new AbortController();
        const timer = setTimeout(() => modelCtrl.abort(), 8500);

        try {
          const groqRes = await fetch("https://api.groq.com/openai/v1/chat/completions", {
            method: "POST",
            headers: {
              Authorization: `Bearer ${activeGroqKey}`,
              "Content-Type": "application/json",
            },
            body: JSON.stringify({
              model: mod,
              messages: [
                { role: "system", content: systemPrompt },
                ...recentMessages,
              ],
              max_tokens: 900,
              temperature: 0.35, // Lower temperature for accurate, focused textbook answers
            }),
            signal: modelCtrl.signal,
          });

          clearTimeout(timer);

          if (groqRes.ok) {
            const gData = await groqRes.json();
            const text = gData?.choices?.[0]?.message?.content?.trim();
            if (text && text.length > 3) {
              return NextResponse.json({
                reply: text,
                source: `groq-${mod}`,
                grade,
                language,
              });
            }
          }
        } catch (modelErr) {
          clearTimeout(timer);
        }
      }
    }

    // 2. Try Anthropic API if configured
    if (envAnthropicKey && envAnthropicKey.startsWith("sk-ant-")) {
      const ctrl = new AbortController();
      const timer = setTimeout(() => ctrl.abort(), 8500);
      try {
        const antRes = await fetch("https://api.anthropic.com/v1/messages", {
          method: "POST",
          headers: {
            "x-api-key": envAnthropicKey,
            "anthropic-version": "2023-06-01",
            "Content-Type": "application/json",
          },
          body: JSON.stringify({
            model: "claude-3-5-haiku-latest",
            max_tokens: 900,
            system: systemPrompt,
            messages: recentMessages.filter((m) => m.content.trim().length > 0),
          }),
          signal: ctrl.signal,
        });
        clearTimeout(timer);
        if (antRes.ok) {
          const aData = await antRes.json();
          const text = aData?.content?.[0]?.text?.trim();
          if (text) {
            return NextResponse.json({
              reply: text,
              source: "anthropic",
              grade,
              language,
            });
          }
        }
      } catch (e) {
        clearTimeout(timer);
      }
    }

    // 3. Direct NIE Teacher Guide Fallback
    const fallbackReply = getDirectTeacherResponse(lastUserMsg, grade, language, messages);
    return NextResponse.json({
      reply: fallbackReply,
      source: "nie-teacher-guide",
      grade,
      language,
    });
  } catch (err) {
    const emergencyReply = getDirectTeacherResponse(lastUserMsg, grade, language, messages);
    return NextResponse.json({
      reply: emergencyReply,
      source: "emergency-fallback",
      grade,
      language,
    });
  }
}
